const T = (value) => ({ type: "text", value });
const B = (...accept) => ({ type: "blank", accept: [...accept] });
const fillLine = (...segments) => ({ segments });

function sci(mantissa, exp) {
  const sign = exp < 0 ? "-" : "";
  const ae = Math.abs(exp);
  return [
    `${mantissa} × 10^${sign}${ae}`,
    `${mantissa} x 10^${sign}${ae}`,
    `${mantissa}*10^${sign}${ae}`,
    `${mantissa}×10^${sign}${ae}`,
    `${mantissa} × 10${sign}${ae}`,
    `${mantissa}e${sign}${ae}`,
    `${mantissa}E${sign}${ae}`,
  ];
}

